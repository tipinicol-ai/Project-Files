const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('projectFilesNative', {
  platform: process.platform,
  getDrives: () => ipcRenderer.invoke('get-drives'),
  getHomePath: () => ipcRenderer.invoke('get-home-path'),
  minimize: () => ipcRenderer.send('window-minimize'),
  toggleMaximize: () => ipcRenderer.send('window-toggle-maximize'),
  close: () => ipcRenderer.send('window-close'),
  chooseFolder: () => ipcRenderer.invoke('choose-folder'),
  chooseFiles: () => ipcRenderer.invoke('choose-files'),
  listDirectory: (folderPath) => ipcRenderer.invoke('list-directory', folderPath),
  openDefault: (filePath) => ipcRenderer.invoke('open-default', filePath),
  showInFolder: (filePath) => ipcRenderer.invoke('show-in-folder', filePath),
  createFolder: (parentPath, name) => ipcRenderer.invoke('create-folder', parentPath, name),
  copy: (sourcePaths, destinationPath, jobId) => ipcRenderer.invoke('copy', sourcePaths, destinationPath, jobId),
  cancelCopy: (jobId) => ipcRenderer.invoke('copy-cancel', jobId),
  readText: (filePath) => ipcRenderer.invoke('read-text', filePath),
  writeText: (filePath, content) => ipcRenderer.invoke('write-text', filePath, content),
  move: (sourcePaths, destinationPath) => ipcRenderer.invoke('move', sourcePaths, destinationPath),
  trash: (filePath) => ipcRenderer.invoke('trash', filePath),
  rename: (filePath, name) => ipcRenderer.invoke('rename', filePath, name),
  readMetadata: (filePath) => ipcRenderer.invoke('read-metadata', filePath),
  compress: (sourcePaths, destinationZip) => ipcRenderer.invoke('compress', sourcePaths, destinationZip),
  extract: (archivePath, destinationPath) => ipcRenderer.invoke('extract', archivePath, destinationPath),
  loadState: () => ipcRenderer.invoke('load-state'),
  saveState: (state) => ipcRenderer.invoke('save-state', state),
  githubList: (username, token) => ipcRenderer.invoke('github-list', username, token),
  githubClone: (cloneUrl, destinationPath) => ipcRenderer.invoke('github-clone', cloneUrl, destinationPath),
  youtubeDownload: (url, quality, mode, destinationPath) => ipcRenderer.invoke('youtube-download', url, quality, mode, destinationPath),
  shareStart: (folderPath, mode) => ipcRenderer.invoke('share-start', folderPath, mode),
  shareStop: () => ipcRenderer.invoke('share-stop'),
  shareStatus: () => ipcRenderer.invoke('share-status'),
})
